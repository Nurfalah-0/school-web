export function getAllGaleri() {
  return [...galeriList].sort((a, b) => new Date(b.tanggal) - new Date(a.tanggal));
}

export function getGaleriByKategori(kategori) {
  return galeriList.filter(g => g.kategori === kategori);
}

export function getKategoriList() {
  return [...kategoriList];
}

export function getFeaturedGaleri(limit = 4) {
  return galeriList.filter(g => g.featured).slice(0, limit);
}
