export function getPrestasiFeatured() {
  return prestasiList.find(p => p.featured) || null;
}

export function getAllPrestasi() {
  return [...prestasiList].sort((a, b) => b.tahun - a.tahun);
}

export function getPrestasiByKategori(kategori) {
  return prestasiList.filter(p => p.kategori === kategori);
}

export function getPrestasiBySlug(slug) {
  return prestasiList.find(p => p.slug === slug) || null;
}

export function getPrestasiLainnya(excludeSlug, limit = 3) {
  return prestasiList
    .filter(p => p.slug !== excludeSlug)
    .sort((a, b) => b.tahun - a.tahun)
    .slice(0, limit);
}
