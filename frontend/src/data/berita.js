export function getBeritaBySlug(slug) {
  return beritaList.find(b => b.slug === slug) || null;
}

export function getAllBerita() {
  return [...beritaList].sort((a, b) => new Date(b.tanggal) - new Date(a.tanggal));
}

export function getBeritaLainnya(excludeSlug, limit = 3) {
  return beritaList
    .filter(b => b.slug !== excludeSlug)
    .sort((a, b) => new Date(b.tanggal) - new Date(a.tanggal))
    .slice(0, limit);
}

export function getBeritaByKategori(kategori) {
  return beritaList.filter(b => b.kategori === kategori);
}

export function getBeritaByTag(tag) {
  return beritaList.filter(b => b.tags && b.tags.includes(tag));
}

export function getBeritaUtama() {
  return beritaList.find(b => b.status === 'UTAMA') || null;
}

export function getBeritaTerbaru(limit = 3) {
  return beritaList
    .filter(b => b.status !== 'UTAMA')
    .sort((a, b) => new Date(b.tanggal) - new Date(a.tanggal))
    .slice(0, limit);
}
